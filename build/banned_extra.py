def build(existing_terms):
    """去掉雷达 174 词里已有的，返回 {groups, terms}。"""
    have = {t.lower() for t in existing_terms}
    out, seen = [], set()
    for word, group, note in TERMS:
        k = word.lower()
        if k in have or k in seen:
            continue
        seen.add(k)
        out.append({'term': word, 'group': group, 'note': note})
    return {'groups': GROUPS, 'terms': out}
