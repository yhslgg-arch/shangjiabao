def _nid(i):
    return f'G{i:04d}'


def apply_names(records):
    """给公开名单追加新词条和写法。返回新 id 列表。"""
    by_name = {r['name']: r for r in records}
    for v, name in VARIANTS:
        r = by_name.get(name)
        assert r, f'补写法找不到词条「{name}」'
        if v not in r['variants']:
            r['variants'].append(v)
    have = {x.lower() for r in records for x in [r['name']] + r['variants']}
    ids = []
    for i, row in enumerate(NAMES, 1):
        name, cat, otype, variants = row[:4]
        labels = list(row[4]) if len(row) > 4 else []
        assert name.lower() not in have, f'「{name}」名单里已有'
        rid = _nid(i)
        records.append({'id': rid, 'name': name, 'variants': [name] + [v for v in variants if v != name], 'category': cat, 'object_type': otype,
                        'companies': [], 'labels': labels, 'registrations': [], 'verification': 'unverified'})
        ids.append(rid)
    return ids


def banned(existing):
    have = {t.lower() for t in existing}
    out, seen = [], set()
    for w, g, note in TERMS:
        k = w.lower()
        if k in have or k in seen:
            continue
        seen.add(k)
        out.append({'term': w, 'group': g, 'note': note})
    return {'groups': GROUPS, 'terms': out}


def apply_phys(phys_ban):
    """把指南的禁售实物词并进 seed4.PHYS_BAN：rx 用来匹配品名，eg 是表里给人看的例子。"""
    hit = set()
    for row in phys_ban:
        add = PHYS_RX.get(row['n'])
        if not add:
            continue
        hit.add(row['n'])
        rx, eg = add
        parts = [p for p in rx.split('|') if p not in row['rx']]
        if parts:
            row['rx'] = row['rx'] + '|' + '|'.join(parts)
        egs = [e for e in eg.split('、') if e not in row['eg']]
        if egs:
            row['eg'] = row['eg'] + '、' + '、'.join(egs)
        row['src2'] = SRC
    assert hit == set(PHYS_RX), set(PHYS_RX) - hit
